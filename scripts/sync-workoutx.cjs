// Generates the static exercise metadata used by the app.
// Run with: node --env-file=.env scripts/sync-workoutx.cjs
// Media URLs are intentionally excluded: they expire and come from /api/exercises.
const fs = require('fs');
const path = require('path');
const { fetchWorkoutXExercises } = require('../server/workoutx');

const apiKey = process.env.WX_API_KEY;
if (!apiKey) {
  console.error('WX_API_KEY is required. Add it to .env or export it in your shell.');
  process.exit(1);
}

(async () => {
  const exercises = await fetchWorkoutXExercises(apiKey);
  const metadata = exercises.map(({ media, ...rest }) => rest);
  const output = [
    '// Generated by scripts/sync-workoutx.cjs. Do not put API keys or expiring media URLs here.',
    `window.WORKOUTX_EXERCISES = ${JSON.stringify(metadata)};`,
    ''
  ].join('\n');
  fs.writeFileSync(path.join(__dirname, '..', 'workoutx-exercises.js'), output);
  console.log(`Wrote ${metadata.length} exercises to workoutx-exercises.js`);
  if (metadata.length < 50) {
    console.warn('Warning: fewer than 50 exercises were returned.');
    process.exitCode = 2;
  }
})().catch(error => {
  console.error(error.message || error);
  process.exit(1);
});
